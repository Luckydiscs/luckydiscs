## The goal of the game

The idea of disc golf is simple. You play each hole from the tee to the basket in as few throws as possible. Every throw counts, and at the end of the round all your throws are added together. Fewer throws means a better score, just like in traditional golf.

## Play order and the tee throw

On the first hole the play order can be decided by lot or agreed within the group. After that the player with the best score on the previous hole throws first. During a hole, the player whose disc is farthest from the basket throws next.

The opening throw, or drive, is always made from the tee. Keep one foot inside the tee area as you throw so that the throw is within the rules.

## Marking your disc and following throws

When your disc comes to rest, that spot is called the lie. Your next throw is made from there. You can mark the spot with a small marker disc and pick up your throwing disc, or simply throw from directly behind the disc.

For a following throw your supporting foot must be right behind the marker or disc, away from the basket. This makes sure every throw starts from the correct spot.

## The putting circle

The putting circle begins roughly ten metres, about thirty three feet, from the basket. This is the most important special rule for a beginner. Inside the circle you may not step past your marker toward the basket until your disc has come to rest in the basket. In other words, there is no follow through past the marker on a putt. Keep your balance and wait until the disc has landed.

## Out of bounds

If your disc lands outside the course, in an out of bounds area, it costs you one penalty throw. You continue play from the point where the disc crossed the out of bounds line. These areas are usually marked with paint or signs, so check them before you throw.

## Completing the hole

A hole is finished when your disc comes to rest in the basket. A valid score means the disc stays in the chains or the tray. If the disc bounces out, you keep playing the hole as normal.

