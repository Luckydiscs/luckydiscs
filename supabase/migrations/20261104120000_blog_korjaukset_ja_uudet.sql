## Plastic and weather

**Freezing temperatures.** All plastic stiffens in the cold. Base plastic holds its grip best, but it is also the most likely to crack in hard frost or on impact. Take discs you would not mind cracking on a winter round, and keep the one you are about to throw warm in your pocket. Our [winter disc golf guide](/blog/winter-disc-golf-play-year-round) has more on playing in the cold.

**Rain and morning dew.** A wet surface is slippery whatever the plastic, but soft base plastic loses the least grip. A towel on your bag helps more than any plastic choice.

**Heat.** A disc left in a hot car or in direct sun can change shape permanently. Keep your discs in the shade.

