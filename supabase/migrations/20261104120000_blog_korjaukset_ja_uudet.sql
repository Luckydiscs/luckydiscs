## A disc doesn't know where the ground is

A disc reacts to how fast air moves past it, not to how fast it moves over the ground.

Into a headwind, air flows past the disc faster than your throwing speed. The disc behaves as if you had thrown it harder: more lift and more tendency to turn right, which means it flies more understable. In a tailwind the opposite happens. Airflow drops, lift drops, and the disc flies more overstable: it fades earlier and lands shorter.

That gives you a rule that feels backwards at first: **into the wind, a more stable disc; downwind, a less stable one.** Throwing harder into the wind does not help. A different disc does.

If flight numbers are still new to you, our [flight numbers guide](/blog/flight-numbers-speed-glide-turn-fade) covers Speed, Glide, Turn and Fade in practice.

## Headwind: less glide, more fade

A headwind punishes two things: too much lift and a nose pointing up.

**Glide works against you.** High glide means the disc stays in the air for a long time even at low speed. Into a headwind it hangs exactly where the wind can work on it. The Treasure Hunt (12 / 6 / -1 / 3) is an excellent distance disc in calm air, but into a strong headwind that same quality turns against it.

**Stability is your friend.** The Money Shot (4 / 3 / 1 / 3) is a good example: turn +1 and fade 3 mean a disc that will not turn right even if you throw it too hard. That is why it works as an approach disc when conditions don't.

**Low line, nose down.** The biggest single mistake into a headwind is a nose-up release. The disc climbs, loses speed, stalls and drops. The same throw released flat or slightly nose-down goes noticeably further. If you are not sure about your nose angle, throw a few discs on a low line and watch which one keeps going and which one climbs.

Rule of thumb: into a headwind, pick the disc that feels too stable in calm air.

## Tailwind: give the disc height

A tailwind sounds easy but is deceptive. The disc gets less lift, fades earlier and lands shorter.

**Throw higher.** Downwind the disc needs more time in the air, and the only way to give it that is height. The same low line lands clearly shorter than in calm air.

**Choose a straighter or less stable disc.** The Jailbreak (5 / 4 / 0 / 2) is a neutral midrange: turn 0 and moderate fade. Downwind it holds its line where an overstable disc would fade out early. For longer holes, throw the Bank Robber (8 / 5 / -1 / 2) flat.

**Expect skips.** A disc landing downwind skips and rolls further. If there is a slope or water behind the basket, aim shorter than feels natural.

## Crosswind: the wind gets under the raised edge

Think of a flying disc as a tilted surface. Wind gets underneath on whichever side is higher and lifts it. On the lower side, it pushes down from above and drops the disc.

**Wind from the right.** On a hyzer line the right edge of the disc is higher, so the wind gets under it. The disc rises, carries further and drifts left. On anhyzer the opposite happens: the wind pushes the disc down and it can roll away. So aim well right, throw hyzer and let the wind bring the disc back toward the basket.

**Wind from the left.** Now the wind gets under a disc on anhyzer and pushes a disc on hyzer down. An understable disc turns even further right and runs away. Aim left and throw a stable or overstable disc flat, so its fade brings it back into the wind at the end of the flight. An overstable approach disc like the Money Shot holds its line well here.

Either way, **aim upwind** and plan a line that drifts toward the basket, not past it.

## Putting in the wind

Wind is harshest on putts, because there is no time to correct.

Into a headwind, putt lower, straighter and firmer so the disc reaches the chains instead of floating where the wind can play with it. Downwind you can use more arc and a softer touch, but remember that a missed putt runs a long way downwind. In a crosswind, the simplest fix is to aim at the upwind edge of the basket.

Grip matters more here than flight numbers. Soft base plastic stays in wet, cold hands better than hard plastic. Our [plastic comparison](/blog/disc-golf-plastic-types-basic-premium-ultrium) goes into the details.

