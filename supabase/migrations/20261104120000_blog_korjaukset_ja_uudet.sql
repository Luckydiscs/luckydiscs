## The goal of the game

The idea is simple. You play each hole from the teeing area to the basket in as few throws as possible. Every throw counts, and at the end of the round they are added up. Fewer throws means a better score, just as in golf.

## Throwing order

In competition, the throwing order on the first hole follows the scorecard. After that, the scores on the previous hole decide who tees off first: the best score goes first, and tied players keep the same order as on the previous tee. Once everyone has teed off, the player whose disc is furthest from the basket always throws next. In a casual group you can agree on the order more freely, as long as nobody throws while someone is ahead on the fairway.

## The tee throw

The tee throw is made from the teeing area. When the disc leaves your hand, all of your supporting points, meaning every part of your body touching the ground or anything else, must be inside the teeing area. After the release you may step outside it.

## Marking your lie and following throws

Once your disc has come to rest, mark its position with a marker disc. The marker goes on the ground directly in front of the disc on the line of play, between the disc and the basket, touching the disc. You can then pick the disc up. If you don't have a marker yet, the [Lucky Discs marker](/shop/lucky-discs-marker) fits in your pocket.

Your lie is the 20 × 30 cm area behind the marker. When you release the disc, at least one supporting point must be on the lie, and no supporting point may be closer to the basket than the rear edge of the marker.

## The putting circle

The putting circle extends 10 metres (33 feet) from the basket. Any throw from within 10 metres of the basket is a putt. After a putt you must show full balance behind your marker before moving towards the basket. You don't have to wait for the disc to come to rest, and shifting your weight forward during the throw is allowed, as long as you don't fall or step past the marker before you are balanced. From outside the circle you may follow through freely.

