Out of bounds (OB) is an area the course defines, such as a road, a ditch or water. The boundaries are usually marked with rope, paint or signs, so check them before your round. If your disc comes to rest out of bounds, you take one penalty throw. You play on either from your previous lie or from up to one metre from where the disc last crossed the OB line. The course's own rules may also provide a drop zone.

## Completing the hole

A hole is finished when your disc comes to rest in the basket, supported by the chains or inside the tray. If the disc bounces out, you play on from where it stopped.

## Etiquette

Good manners make the sport enjoyable for everyone. Stay quiet and still while another player is throwing. Let a faster group play through if yours is slow. Take your rubbish with you and leave the hole tidier than you found it.

