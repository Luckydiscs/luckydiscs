The difference was not arm speed. It was decisions.

Many wasted strokes at beginner and intermediate level do not come from throws that were too short. They come from discs thrown to the wrong place, or to the right place with too much risk. Adding distance takes months. Better decisions can start on your next round.

Here are six rules that show up on your scorecard before your technique has time to change. The examples assume a right-handed backhand throw.

## 1. Throw at an area, not in a direction

Before every throw, ask: **where do I want this disc to land?**

The answer is not a direction such as "left" or "towards the basket" but a specific area: the gap between that stump and the bush, the opening to the right of the big spruce, the bend in the path.

The difference matters, because "towards the basket" tells you nothing about whether the throw worked. A landing zone does. If you cannot name the area, you have not read the hole yet, you have only looked at it.

Once the area is chosen, the disc often chooses itself. If the zone is 70 metres out through a narrow gap, the question is no longer "how far can I throw" but "which disc gets me in there". The Jailbreak (5 / 4 / 0 / 2) is made for this: a neutral midrange that goes where you point it instead of turning on the way.

## 2. Play for par, not for the highlight reel

Every hole has two versions: the one you play when everything works, and the one you play when the throw comes out a bit short of what you intended.

Your score nearly always comes from the second one.

Imagine throwing the same shot ten times. How many go as planned? If the answer is two or three, that is not a plan, it is a gamble. Usually a bad one, because the cost of failure is far bigger than the reward: the disc ends up behind water, deep in the brush or out of bounds, and all you stood to gain was one throw's worth of distance.

This is not an argument for timid golf. Take the risk where it pays: on a long par 4 with a genuinely open gap, not on a par 3 where a safe three is waiting.

## 3. Know the hole's punishing side

On almost every hole, one side punishes a miss far harder than the other. One side has thick forest, a slope, a ditch or an OB line. The other has grass and a dull but playable next shot.

**Always aim your miss at the friendly side.**

If water is on the right, do not throw a line that curves right "just a little". Throw a line whose natural miss goes left. For a right-handed backhand thrower that often means a hyzer line: a disc with clear fade misses in a predictable direction.

This is where overstability earns its place. The Money Shot (4 / 3 / 1 / 3) is a good example: turn +1 and fade 3 mean a disc that will not run away to the right even when you throw it too hard. It is not the longest disc in the bag, but it is the most predictable, and predictability is what strategy is built from. If flight numbers are still new to you, our [flight numbers guide](/blog/flight-numbers-speed-glide-turn-fade) explains them in practice.

## 4. The layup is a skill, not a surrender

You are 25 metres from the basket. There is a tangle of branches in front of you and a downhill slope behind the basket.

**Option A:** throw straight at the basket through the branches. Sometimes it works. When it does not, the disc ricochets somewhere random or rolls down the slope behind the basket.

**Option B:** throw a safe shot to a couple of metres in front of the basket and putt it in.

Option B is usually right, and still rarely chosen, because it feels passive. But the scorecard does not ask whether the throw looked good.

Rule of thumb: if a failed attempt leaves you out of bounds or so far away that the comeback putt is hard, the attempt is usually not worth the risk. The layup is not the throw that loses you the round. It is the throw that keeps the round under control.

## 5. Play the hole backwards

Experienced players do not plan a hole from tee to basket. They plan it from the basket back to the tee.

Ask first: **where do I want to putt from?** Then: how do I get there? And only last: which drive puts me in that spot?

That turns the logic around. If you want to putt from open ground in front of the basket, and the best way there is from the left side of the fairway, your drive's job is to reach the left side, not to travel as far as possible. A controlled 90-metre throw with the Bank Robber (8 / 5 / -1 / 2) then beats a 120-metre throw that leaves you behind a tree.

On long holes distance does matter, and that is where the Treasure Hunt (12 / 6 / -1 / 3) does its job. But distance is a means, not the goal. The goal is a good putting position.

## 6. One disc you know beats five you own

Strategy needs predictability, and predictability comes from repetition. A player who knows one midrange inside out makes better decisions than a player with ten discs and a vague idea of each.

The drill: play one round with three discs. Putter, midrange and fairway driver, no distance driver at all.

At first the round feels restrictive. Then you notice two things. Your score probably does not collapse, and it may even improve. And you learn what your discs really do, because you have to use them in situations where you would normally reach for something else.

