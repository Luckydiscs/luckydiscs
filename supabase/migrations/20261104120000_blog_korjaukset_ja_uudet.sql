## What plastic changes

Flight numbers belong to the mould, but plastic affects how the disc actually flies and how long it stays that way. The difference comes down to three things.

**Wear.** Every tree and rock hit reshapes the rim and dome slightly. Soft plastic changes quickly, hard plastic slowly. As a disc wears it becomes more understable, which means it turns right more easily than it did when new.

**Grip.** The surface and softness of the plastic decide how well the disc stays in your fingers when it is cold or damp.

**Shape out of the mould.** Different plastics settle in the mould slightly differently, so discs from the same mould can fly a little differently even when new. That is why it pays to throw a disc yourself rather than rely on the numbers alone.

